"""Convert your SQLite schema.sql into schema_postgres.sql (what server.py loads).

    python make_postgres_schema.py database/schema.sql database/schema_postgres.sql

It runs your SQLite file in memory, then writes the same locations and employees as
Postgres-ready SQL. It also writes locations_to_geocode.csv (next to the output file)
in the US Census batch-geocoder format, so you can get real facility coordinates.
"""
import csv
import sqlite3
import sys
from pathlib import Path

if len(sys.argv) != 3:
    raise SystemExit(__doc__)
source, target = Path(sys.argv[1]), Path(sys.argv[2])

db = sqlite3.connect(":memory:")
db.executescript(source.read_text(encoding="utf-8"))
locations = db.execute("SELECT location_id, name, address FROM locations ORDER BY location_id").fetchall()
employees = db.execute(
    "SELECT user_id, location_id, full_name, shift_start, shift_end, days_of_week "
    "FROM employees ORDER BY user_id").fetchall()


def q(value):
    return "'" + str(value).replace("'", "''") + "'"


def batches(rows, size=500):
    for i in range(0, len(rows), size):
        yield rows[i:i + size]


out = ["""-- Generated by make_postgres_schema.py. Loaded once by server.py on an empty database.
CREATE TABLE locations (
  location_id INTEGER PRIMARY KEY CHECK (location_id BETWEEN 1 AND 200),
  name TEXT NOT NULL UNIQUE,
  address TEXT NOT NULL DEFAULT ''
);

CREATE TABLE employees (
  user_id TEXT PRIMARY KEY CHECK (user_id ~ '^[0-9]{6}$'),
  location_id INTEGER NOT NULL REFERENCES locations(location_id),
  full_name TEXT NOT NULL,
  shift_start TEXT NOT NULL CHECK (shift_start ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  shift_end TEXT NOT NULL CHECK (shift_end ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  days_of_week TEXT NOT NULL CHECK (days_of_week IN
    ('Mon-Fri','Mon-Thu','Tue-Sat','Wed-Sun','Tue-Fri','Sun-Thu')),
  CHECK (shift_end > shift_start)
);
CREATE INDEX ix_employees_location ON employees(location_id);
"""]

for chunk in batches(locations):
    out.append("INSERT INTO locations (location_id, name, address) VALUES\n  " +
               ",\n  ".join(f"({r[0]}, {q(r[1])}, {q(r[2])})" for r in chunk) + ";\n")
for chunk in batches(employees):
    out.append("INSERT INTO employees (user_id, location_id, full_name, shift_start, shift_end, days_of_week) VALUES\n  " +
               ",\n  ".join(f"({q(r[0])}, {r[1]}, {q(r[2])}, {q(r[3])}, {q(r[4])}, {q(r[5])})" for r in chunk) + ";\n")

target.write_text("\n".join(out), encoding="utf-8")

# Census batch geocoder input: Unique ID, Street address, City, State, ZIP (no header row).
geocode_path = target.with_name("locations_to_geocode.csv")
skipped = []
with geocode_path.open("w", newline="", encoding="utf-8") as f:
    writer = csv.writer(f)
    for location_id, _, address in locations:
        parts = [p.strip() for p in address.split(",")]
        if len(parts) < 3 or len(parts[-1].split()) != 2:
            skipped.append(location_id)
            continue
        state, zip_code = parts[-1].split()
        writer.writerow([location_id, ", ".join(parts[:-2]), parts[-2], state, zip_code])

print(f"Wrote {target}: {len(locations)} locations, {len(employees)} employees.")
print(f"Wrote {geocode_path}" + (f" (could not parse locations {skipped})" if skipped else ""))